			menuTween:Play()
			darkenTween:Play()
	
			-- Hide both frames once the tweens finish
			task.delay(tweenInfo.Time, function()
				if not isOpen then
					menuFrame.Visible = false
					darkenEffect.Visible = false
				end
			end)
